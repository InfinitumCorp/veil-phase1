"""bootstrap.sh end to end, against local copies of the upstream repositories.

Needs two checkouts that aren't part of this repository (they hold upstream
source), named by environment variables:

  VEIL_UPSTREAM_SUBSET  git repo from import_upstream_subset.py (branch "upstream")
  VEIL_UPSTREAM_TBB     tor-browser-build clone with tag tbb-16.0-build1

Runs bootstrap with --pending (the series awaiting review) and a throwaway
registry signing key, then checks that tor-browser carries VEIL's patches and
the verified registry, and that tor-browser-build is set up to build that
exact commit.
"""
import os
import shutil
import subprocess
from pathlib import Path

import pytest

SUBSET = os.environ.get("VEIL_UPSTREAM_SUBSET")
TBB = os.environ.get("VEIL_UPSTREAM_TBB")

pytestmark = pytest.mark.skipif(not (SUBSET and TBB and Path(SUBSET).is_dir() and Path(TBB).is_dir()),
                                reason="set VEIL_UPSTREAM_SUBSET and VEIL_UPSTREAM_TBB to run")


def git(*args, cwd=None):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True).stdout


def test_bootstrap_builds_the_veil_branch(root, tmp_path):
    work = tmp_path / "veil"
    ignore = shutil.ignore_patterns("work", ".demo-data", "__pycache__", ".pytest_cache")
    for part in ("veil-build", "veil-browser", "veil-chrome"):
        shutil.copytree(root / part, work / part, ignore=ignore)

    # "Upstream" tor-browser: the verified subset, tagged like the real release.
    browser = tmp_path / "tor-browser.git"
    git("clone", "-q", "--bare", "-b", "upstream", SUBSET, str(browser))
    conf = (work / "veil-build" / "veil.conf").read_text()
    tag = next(l.split("=", 1)[1] for l in conf.splitlines() if l.startswith("TOR_BROWSER_TAG="))
    git("tag", tag, "upstream", cwd=browser)
    conf = "\n".join(
        f"TOR_BROWSER_URL=file://{browser}" if l.startswith("TOR_BROWSER_URL=") else
        f"TOR_BROWSER_BUILD_URL=file://{Path(TBB).resolve()}" if l.startswith("TOR_BROWSER_BUILD_URL=") else l
        for l in conf.splitlines()) + "\n"
    (work / "veil-build" / "veil.conf").write_text(conf)

    # A throwaway key signs the app registry.
    tool = work / "veil-chrome" / "tools" / "registry_tool.py"
    subprocess.run(["python3", str(tool), "keygen", str(tmp_path / "keys" / "test")], check=True, capture_output=True)
    shutil.copy(tmp_path / "keys" / "test.pub", work / "veil-chrome" / "registry" / "keys" / "test.pub")
    subprocess.run(["python3", str(tool), "sign", str(work / "veil-chrome" / "registry" / "registry.json"),
                    str(tmp_path / "keys" / "test.key")], check=True, capture_output=True)

    out = tmp_path / "out"
    r = subprocess.run(["bash", str(work / "veil-build" / "bootstrap.sh"), "--work-dir", str(out),
                        "--skip-verify", "--pending"], capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr

    tb = out / "tor-browser"
    subjects = git("log", "--format=%s", f"refs/tags/{tag}..HEAD", cwd=tb).splitlines()[::-1]
    assert subjects == [
        "VEIL branding for the release channel",
        "VEIL start page, sign-in and app side panel",
        "Anonymity guard: go offline if Tor could be bypassed",
        "Remove the way to run with Tor turned off",
        "Address-bar commands for VEIL's apps",
        "VEIL app registry (verified, generated by bootstrap.sh)",
    ]
    assert (tb / "browser/components/veil/content/generated/registry.json").is_file()
    head = git("rev-parse", "HEAD", cwd=tb).strip()

    local = (out / "tor-browser-build" / "rbm.local.conf").read_text()
    assert f"veil_browser_commit: '{head}'" in local
    assert f"veil_browser_git_url: '{tb}'" in local
    cfg = (out / "tor-browser-build" / "projects" / "firefox" / "config").read_text()
    assert "git_hash: '[% c(\"var/veil_browser_commit\") %]'" in cfg
    assert "update.veil.invalid" in cfg and "aus1.torproject.org" not in cfg

    pin = (out / "pin.lock").read_text()
    assert f"veil_browser_head={head}" in pin and "veil_patches=pending-review" in pin

    # Running bootstrap again gives the same branch, not patches applied twice.
    r2 = subprocess.run(["bash", str(work / "veil-build" / "bootstrap.sh"), "--work-dir", str(out),
                         "--skip-verify", "--pending"], capture_output=True, text=True)
    assert r2.returncode == 0, r2.stdout + r2.stderr
    assert git("rev-parse", "HEAD^{tree}", cwd=tb) == git("rev-parse", f"{head}^{{tree}}", cwd=tb)


def test_bootstrap_refuses_an_unsigned_registry(root, tmp_path):
    work = tmp_path / "veil"
    ignore = shutil.ignore_patterns("work", ".demo-data", "__pycache__", ".pytest_cache")
    for part in ("veil-build", "veil-browser", "veil-chrome"):
        shutil.copytree(root / part, work / part, ignore=ignore)
    browser = tmp_path / "tor-browser.git"
    git("clone", "-q", "--bare", "-b", "upstream", SUBSET, str(browser))
    conf = (work / "veil-build" / "veil.conf").read_text()
    tag = next(l.split("=", 1)[1] for l in conf.splitlines() if l.startswith("TOR_BROWSER_TAG="))
    git("tag", tag, "upstream", cwd=browser)
    conf = "\n".join(
        f"TOR_BROWSER_URL=file://{browser}" if l.startswith("TOR_BROWSER_URL=") else
        f"TOR_BROWSER_BUILD_URL=file://{Path(TBB).resolve()}" if l.startswith("TOR_BROWSER_BUILD_URL=") else l
        for l in conf.splitlines()) + "\n"
    (work / "veil-build" / "veil.conf").write_text(conf)
    sig = work / "veil-chrome" / "registry" / "registry.json.sig"
    sig.unlink(missing_ok=True)
    r = subprocess.run(["bash", str(work / "veil-build" / "bootstrap.sh"), "--work-dir", str(tmp_path / "out"),
                        "--skip-verify", "--pending"], capture_output=True, text=True)
    assert r.returncode != 0
    assert "not signed by a VEIL key" in r.stderr


def test_committed_patches_match_a_fresh_cut(root, tmp_path):
    """The pending patches are exactly what cut_patches.py makes from today's sources."""
    for tree_env, script, committed in (
            (SUBSET, "veil-browser/tools/cut_patches.py", "veil-browser/patches/pending"),
            (TBB, "veil-build/tools/cut_build_patches.py", "veil-build/patches/pending")):
        tree = tmp_path / Path(script).stem
        git("clone", "-q", tree_env, str(tree))
        base = "upstream" if tree_env == SUBSET else "tbb-16.0-build1"
        git("checkout", "-q", "-B", "cut", base, cwd=tree)
        out = tmp_path / (Path(script).stem + "-out")
        r = subprocess.run(["python3", "-I", str(root / script), str(tree), str(out)], capture_output=True, text=True)
        assert r.returncode == 0, r.stderr
        for f in sorted((root / committed).iterdir()):
            assert (out / f.name).read_bytes() == f.read_bytes(), f"{committed}/{f.name} is stale: rerun {script}"
